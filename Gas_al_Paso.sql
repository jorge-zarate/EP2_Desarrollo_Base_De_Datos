-- Tablas
CREATE TABLE Tienda (
    id_tienda NUMBER PRIMARY KEY,
    nombre_tienda VARCHAR2(50) NOT NULL
);

CREATE TABLE Empleado (
    id_empleado NUMBER PRIMARY KEY,
    nombre VARCHAR2(80) NOT NULL,
    id_tienda NUMBER NOT NULL,
    CONSTRAINT fk_empleado_tienda FOREIGN KEY (id_tienda)
        REFERENCES Tienda(id_tienda)
);

CREATE TABLE Productos (
    id_producto NUMBER PRIMARY KEY,
    nombre VARCHAR2(50) NOT NULL,
    descripcion VARCHAR2(100) NOT NULL,
    peso NUMBER(5,2) NOT NULL,
    valor_unitario NUMBER(10,2) NOT NULL,
    stock NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT ck_productos_precio CHECK (valor_unitario > 0),
    CONSTRAINT ck_productos_stock CHECK (stock >= 0 AND stock = TRUNC(stock))
);

CREATE TABLE Venta (
    id_venta NUMBER PRIMARY KEY,
    fecha_venta DATE DEFAULT SYSDATE NOT NULL,
    id_empleado NUMBER NOT NULL,
    id_tienda NUMBER NOT NULL,
    subtotal NUMBER(12,2) DEFAULT 0 NOT NULL,
    descuento NUMBER(12,2) DEFAULT 0 NOT NULL,
    total_venta NUMBER(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT fk_venta_empleado FOREIGN KEY (id_empleado)
        REFERENCES Empleado(id_empleado),
    CONSTRAINT fk_venta_tienda FOREIGN KEY (id_tienda)
        REFERENCES Tienda(id_tienda),
    CONSTRAINT ck_venta_importes CHECK (
        subtotal >= 0 AND descuento BETWEEN 0 AND subtotal
        AND total_venta = subtotal - descuento
    )
);

CREATE TABLE Detalle_venta (
    id_detalle NUMBER PRIMARY KEY,
    id_venta NUMBER NOT NULL,
    id_producto NUMBER NOT NULL,
    cantidad NUMBER NOT NULL,
    precio_unitario NUMBER(10,2) NOT NULL,
    subtotal NUMBER(12,2) NOT NULL,
    descuento NUMBER(12,2) NOT NULL,
    total_venta NUMBER(12,2) NOT NULL,
    CONSTRAINT fk_detalle_venta FOREIGN KEY (id_venta)
        REFERENCES Venta(id_venta),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (id_producto)
        REFERENCES Productos(id_producto),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0 AND cantidad = TRUNC(cantidad)),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario > 0),
    CONSTRAINT ck_detalle_importes CHECK (
        subtotal = precio_unitario * cantidad
        AND descuento BETWEEN 0 AND subtotal
        AND total_venta = subtotal - descuento
    )
);

CREATE TABLE Auditoria_Precio (
    id_auditoria NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto NUMBER NOT NULL,
    precio_anterior NUMBER(10,2) NOT NULL,
    precio_nuevo NUMBER(10,2) NOT NULL,
    fecha_cambio DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_auditoria_producto FOREIGN KEY (id_producto)
        REFERENCES Productos(id_producto)
);

CREATE SEQUENCE seq_venta START WITH 1 INCREMENT BY 1 NOCACHE;
