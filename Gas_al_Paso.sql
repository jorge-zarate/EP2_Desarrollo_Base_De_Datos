-- Caso 1: calcular compra y descuento
CREATE OR REPLACE FUNCTION CalcularSubtotal (
    p_id_producto IN NUMBER,
    p_cantidad IN NUMBER
) RETURN NUMBER IS
    v_precio Productos.valor_unitario%TYPE;
BEGIN
    IF p_cantidad IS NULL OR p_cantidad <= 0 OR p_cantidad <> TRUNC(p_cantidad) THEN
        RAISE_APPLICATION_ERROR(-20001, 'La cantidad debe ser un entero mayor que cero');
    END IF;
    SELECT valor_unitario INTO v_precio
    FROM Productos WHERE id_producto = p_id_producto;
    RETURN ROUND(v_precio * p_cantidad, 2);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20002, 'El producto no existe');
END CalcularSubtotal;
/

CREATE OR REPLACE FUNCTION CalcularDescuento (
    p_subtotal IN NUMBER
) RETURN NUMBER IS
BEGIN
    IF p_subtotal >= 30000 THEN
        RETURN ROUND(p_subtotal * 0.10, 2);
    END IF;
    RETURN 0;
END CalcularDescuento;
/

