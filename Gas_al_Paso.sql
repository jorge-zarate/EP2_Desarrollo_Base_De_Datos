CREATE OR REPLACE PACKAGE PkgVentas IS
    PROCEDURE RegistrarVenta (
        p_id_empleado IN NUMBER,
        p_id_producto IN NUMBER,
        p_cantidad IN NUMBER,
        p_id_venta OUT NUMBER
    );
END PkgVentas;
/

CREATE OR REPLACE PACKAGE BODY PkgVentas IS
    PROCEDURE ValidarDatos (
        p_id_empleado IN NUMBER,
        p_id_producto IN NUMBER,
        p_cantidad IN NUMBER,
        p_id_tienda OUT NUMBER,
        p_precio OUT NUMBER
    ) IS
    BEGIN
        IF p_cantidad IS NULL OR p_cantidad <= 0 OR p_cantidad <> TRUNC(p_cantidad) THEN
            RAISE_APPLICATION_ERROR(-20001, 'La cantidad debe ser un entero mayor que cero');
        END IF;
        SELECT id_tienda INTO p_id_tienda
        FROM Empleado WHERE id_empleado = p_id_empleado;
        SELECT valor_unitario INTO p_precio
        FROM Productos WHERE id_producto = p_id_producto;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20005, 'No existe el empleado o producto indicado');
    END ValidarDatos;

    PROCEDURE RegistrarVenta (
        p_id_empleado IN NUMBER,
        p_id_producto IN NUMBER,
        p_cantidad IN NUMBER,
        p_id_venta OUT NUMBER
    ) IS
        v_id_tienda Empleado.id_tienda%TYPE;
        v_precio Productos.valor_unitario%TYPE;
        v_subtotal NUMBER(12,2);
        v_descuento NUMBER(12,2);
    BEGIN
        SAVEPOINT inicio_venta;
        ValidarDatos(p_id_empleado, p_id_producto, p_cantidad, v_id_tienda, v_precio);
        v_subtotal := ROUND(v_precio * p_cantidad, 2);
        v_descuento := CalcularDescuento(v_subtotal);
        p_id_venta := seq_venta.NEXTVAL;

        INSERT INTO Venta (id_venta, fecha_venta, id_empleado, id_tienda, subtotal, descuento, total_venta)
        VALUES (p_id_venta, SYSDATE, p_id_empleado, v_id_tienda,
                v_subtotal, v_descuento, v_subtotal - v_descuento);

        INSERT INTO Detalle_venta (
            id_detalle, id_venta, id_producto, cantidad,
            precio_unitario, subtotal, descuento, total_venta
        ) VALUES (
            seq_detalle_venta.NEXTVAL, p_id_venta, p_id_producto, p_cantidad,
            v_precio, v_subtotal, v_descuento, v_subtotal - v_descuento
        );

        DBMS_OUTPUT.PUT_LINE('Venta ' || p_id_venta || ' registrada. Total: $' || (v_subtotal - v_descuento));
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO inicio_venta;
            RAISE;
    END RegistrarVenta;
END PkgVentas;
/

-- Caso 3: boleta y resumen del dia
CREATE OR REPLACE PROCEDURE MostrarBoleta (
    p_id_venta IN NUMBER
) IS
    v_empleado Empleado.nombre%TYPE;
    v_tienda Tienda.nombre_tienda%TYPE;
    v_fecha Venta.fecha_venta%TYPE;
    v_subtotal Venta.subtotal%TYPE;
    v_descuento Venta.descuento%TYPE;
    v_total Venta.total_venta%TYPE;
    v_hay_detalle BOOLEAN := FALSE;
BEGIN
    SELECT e.nombre, t.nombre_tienda, v.fecha_venta, v.subtotal, v.descuento, v.total_venta
    INTO v_empleado, v_tienda, v_fecha, v_subtotal, v_descuento, v_total
    FROM Venta v
    JOIN Empleado e ON e.id_empleado = v.id_empleado
    JOIN Tienda t ON t.id_tienda = v.id_tienda
    WHERE v.id_venta = p_id_venta;

    DBMS_OUTPUT.PUT_LINE('----- BOLETA GAS AL PASO -----');
    DBMS_OUTPUT.PUT_LINE('Folio: ' || p_id_venta);
    DBMS_OUTPUT.PUT_LINE('Fecha: ' || TO_CHAR(v_fecha, 'DD-MM-YYYY HH24:MI'));
    DBMS_OUTPUT.PUT_LINE('Empleado: ' || v_empleado);
    DBMS_OUTPUT.PUT_LINE('Sucursal: ' || v_tienda);

    FOR r IN (
        SELECT p.nombre, d.cantidad, d.precio_unitario,
               d.subtotal, d.descuento, d.total_venta
        FROM Detalle_venta d
        JOIN Productos p ON p.id_producto = d.id_producto
        WHERE d.id_venta = p_id_venta
        ORDER BY d.id_detalle
    ) LOOP
        v_hay_detalle := TRUE;
        DBMS_OUTPUT.PUT_LINE(r.nombre || ' x ' || r.cantidad || ' a $' || r.precio_unitario);
        DBMS_OUTPUT.PUT_LINE('Subtotal $' || r.subtotal || ' Descuento $' || r.descuento || ' Total $' || r.total_venta);
    END LOOP;
    IF NOT v_hay_detalle THEN
        RAISE_APPLICATION_ERROR(-20006, 'La venta no tiene productos asociados');
    END IF;
    DBMS_OUTPUT.PUT_LINE('TOTAL BOLETA: $' || v_total);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('La venta ' || p_id_venta || ' no existe');
END MostrarBoleta;
/

CREATE OR REPLACE FUNCTION TotalVendidoHoy RETURN NUMBER IS
    v_total NUMBER;
BEGIN
    SELECT NVL(SUM(total_venta), 0) INTO v_total
    FROM Venta
    WHERE fecha_venta >= TRUNC(SYSDATE)
      AND fecha_venta < TRUNC(SYSDATE) + 1;
    RETURN v_total;
END TotalVendidoHoy;
/

CREATE OR REPLACE PROCEDURE ResumenHoy IS
    CURSOR c_ventas IS
        SELECT id_venta, total_venta
        FROM Venta
        WHERE fecha_venta >= TRUNC(SYSDATE)
          AND fecha_venta < TRUNC(SYSDATE) + 1
        ORDER BY id_venta;
    v_cantidad NUMBER := 0;
    v_total NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('----- RESUMEN DEL DIA ' || TO_CHAR(SYSDATE, 'DD-MM-YYYY') || ' -----');
    FOR r IN c_ventas LOOP
        v_cantidad := v_cantidad + 1;
        v_total := v_total + r.total_venta;
        DBMS_OUTPUT.PUT_LINE('Venta ' || r.id_venta || ': $' || r.total_venta);
    END LOOP;
    DBMS_OUTPUT.PUT_LINE('Ventas de hoy: ' || v_cantidad);
    DBMS_OUTPUT.PUT_LINE('Total vendido: $' || v_total);
    DBMS_OUTPUT.PUT_LINE('Control: $' || TotalVendidoHoy);
END ResumenHoy;
/

CREATE OR REPLACE PROCEDURE ResumenEmpleado (
    p_id_empleado IN NUMBER
) IS
    v_nombre Empleado.nombre%TYPE;
    v_cantidad NUMBER;
    v_total NUMBER;
BEGIN
    SELECT nombre INTO v_nombre FROM Empleado WHERE id_empleado = p_id_empleado;
    SELECT COUNT(*), NVL(SUM(total_venta), 0)
    INTO v_cantidad, v_total
    FROM Venta
    WHERE id_empleado = p_id_empleado
      AND fecha_venta >= TRUNC(SYSDATE)
      AND fecha_venta < TRUNC(SYSDATE) + 1;
    DBMS_OUTPUT.PUT_LINE('Empleado: ' || v_nombre);
    DBMS_OUTPUT.PUT_LINE('Ventas de hoy: ' || v_cantidad);
    DBMS_OUTPUT.PUT_LINE('Total vendido: $' || v_total);
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('El empleado no existe');
END ResumenEmpleado;
/

